"""
Robust Parser for textual LLVM IR (.ll) files generated by Clang.
"""
import re
from typing import List, Optional
from src.llvm.ir_nodes import (
    IRModule, IRFunction, IRBasicBlock, IRInstruction, IROperand
)


class IRParser:
    def __init__(self, text: str):
        # Canonicalize numeric temporaries (%0 -> %_t0) and labels (13: -> bb_13:)
        # to ensure LLVM accepts IR even after passes delete dead instructions
        text = re.sub(r'label\s+%(\d+)\b', r'label %bb_\1', text)
        text = re.sub(r'(?m)^(\d+):', r'bb_\1:', text)
        text = re.sub(r'(?m)^;\s*<label>:(\d+):?', r'bb_\1:', text)
        text = re.sub(r'%(\d+)\b', r'%_t\1', text)
        self.text = text
        self.lines = text.splitlines()

    def parse(self) -> IRModule:
        module = IRModule()
        in_function = False
        current_func: Optional[IRFunction] = None
        current_block: Optional[IRBasicBlock] = None
        current_func_attrs: List[str] = []

        i = 0
        while i < len(self.lines):
            line = self.lines[i]
            stripped = line.strip()

            if not stripped:
                i += 1
                continue

            # Header info before functions
            if not in_function and stripped.startswith("source_filename"):
                module.source_filename = line
                module.raw_header_lines.append(line)
                i += 1
                continue
            elif not in_function and stripped.startswith("target datalayout"):
                module.target_datalayout = line
                module.raw_header_lines.append(line)
                i += 1
                continue
            elif not in_function and stripped.startswith("target triple"):
                module.target_triple = line
                module.raw_header_lines.append(line)
                i += 1
                continue
            elif not in_function and (stripped.startswith("; ModuleID") or stripped.startswith(";")):
                # Comment before function
                if stripped.startswith("; Function Attrs:"):
                    current_func_attrs.append(line)
                else:
                    module.raw_header_lines.append(line)
                i += 1
                continue

            # Global variables
            if not in_function and (stripped.startswith("@") and (" = " in stripped)):
                module.global_vars.append(line)
                i += 1
                continue

            # Metadata and attributes after functions
            if not in_function and (stripped.startswith("attributes #") or stripped.startswith("!") or stripped.startswith(";")):
                module.metadata_lines.append(line)
                i += 1
                continue

            # Function declaration (declare ...)
            if not in_function and stripped.startswith("declare "):
                func_decl = self._parse_function_declaration(line)
                module.functions.append(func_decl)
                i += 1
                continue

            # Function definition (define ...)
            if not in_function and stripped.startswith("define "):
                in_function = True
                current_func = self._parse_function_header(line, current_func_attrs)
                current_func_attrs = []
                # Implicit entry block for instructions before first explicit label
                current_block = IRBasicBlock(name="entry")
                current_func.blocks.append(current_block)
                i += 1
                continue

            # Inside function
            if in_function:
                if stripped == "}":
                    # End of function
                    # If entry block was empty and subsequent blocks exist, remove empty entry
                    if (len(current_func.blocks) > 1 and 
                        current_func.blocks[0].name == "entry" and 
                        len(current_func.blocks[0].instructions) == 0):
                        current_func.blocks.pop(0)

                    module.functions.append(current_func)
                    in_function = False
                    current_func = None
                    current_block = None
                    i += 1
                    continue

                # Check for block label
                label_match = re.match(r"^([a-zA-Z0-9_.\-]+):", stripped)
                numeric_label_match = re.match(r"^;\s*<label>:(\d+):?", stripped)
                num_only_match = re.match(r"^(\d+):", stripped)

                if label_match:
                    label_name = label_match.group(1)
                    current_block = IRBasicBlock(name=label_name)
                    current_func.blocks.append(current_block)
                    i += 1
                    continue
                elif numeric_label_match:
                    label_name = numeric_label_match.group(1)
                    current_block = IRBasicBlock(name=label_name)
                    current_func.blocks.append(current_block)
                    i += 1
                    continue
                elif num_only_match:
                    label_name = num_only_match.group(1)
                    current_block = IRBasicBlock(name=label_name)
                    current_func.blocks.append(current_block)
                    i += 1
                    continue

                # Skip comment-only lines inside function
                if stripped.startswith(";"):
                    i += 1
                    continue

                # Instruction
                inst = self._parse_instruction(line)
                if current_block is None:
                    current_block = IRBasicBlock(name="entry")
                    current_func.blocks.append(current_block)
                current_block.add_instruction(inst)
                i += 1
                continue

            i += 1

        self._resolve_cfg(module)
        return module

    def _parse_function_declaration(self, line: str) -> IRFunction:
        # declare [attrs] <ret_type> @<name>(<args>) [attrs]
        match = re.search(r"declare\s+(?:[a-zA-Z0-9_()]+\s+)*([\w\*\d]+)\s+@([\w\.\-]+)\((.*?)\)", line)
        if match:
            ret_ty = match.group(1)
            name = match.group(2)
            args_str = match.group(3)
            return IRFunction(
                name=name,
                return_type=ret_ty,
                is_declaration=True,
                raw_header=line
            )
        return IRFunction(name="unknown_decl", is_declaration=True, raw_header=line)

    def _parse_function_header(self, line: str, attrs: List[str]) -> IRFunction:
        # define [attrs] <ret_ty> @<name>(<args>) [attrs] {
        match = re.search(r"define\s+(?:[a-zA-Z0-9_()]+\s+)*([\w\*\d]+)\s+@([\w\.\-]+)\((.*?)\)", line)
        if match:
            ret_ty = match.group(1)
            name = match.group(2)
            args_str = match.group(3)
            args = []
            if args_str.strip():
                for arg_item in args_str.split(","):
                    parts = arg_item.strip().split()
                    if len(parts) >= 2:
                        args.append(IROperand(type=parts[0], value=parts[-1]))
                    elif len(parts) == 1:
                        args.append(IROperand(type=parts[0], value=""))
            return IRFunction(
                name=name,
                return_type=ret_ty,
                arguments=args,
                attributes=attrs,
                is_declaration=False,
                raw_header=line
            )
        return IRFunction(name="unknown_func", attributes=attrs, raw_header=line)

    def _parse_instruction(self, line: str) -> IRInstruction:
        raw_line = line
        comment = ""
        if ";" in line:
            parts = line.split(";", 1)
            line_code = parts[0].strip()
            comment = parts[1].strip()
        else:
            line_code = line.strip()

        result = None
        body = line_code
        if "=" in line_code:
            lhs, rhs = line_code.split("=", 1)
            result = lhs.strip()
            body = rhs.strip()

        tokens = body.split()
        if not tokens:
            return IRInstruction(opcode="nop", raw_text=raw_line)

        opcode = tokens[0]
        operands: List[IROperand] = []

        # Parse common operands
        # e.g. "add nsw i32 %4, 1"
        # e.g. "store i32 %0, ptr %2, align 4"
        # e.g. "br i1 %cmp, label %8, label %12"
        # e.g. "br label %8"
        # e.g. "ret i32 %sum"
        rest = " ".join(tokens[1:])
        
        if opcode == "br":
            # br label %8 or br i1 %cmp, label %8, label %12
            labels = re.findall(r"label\s+%?([\w\.\-]+)", rest)
            cond = re.search(r"i1\s+(%\w+)", rest)
            if cond and len(labels) == 2:
                operands.append(IROperand(type="i1", value=cond.group(1)))
                operands.append(IROperand(type="label", value=labels[0]))
                operands.append(IROperand(type="label", value=labels[1]))
            elif labels:
                operands.append(IROperand(type="label", value=labels[0]))
        elif opcode == "ret":
            # ret i32 %4 or ret void
            if "void" in rest:
                operands.append(IROperand(type="void", value=""))
            else:
                ret_parts = rest.split()
                if len(ret_parts) >= 2:
                    operands.append(IROperand(type=ret_parts[0], value=ret_parts[1]))
                elif ret_parts:
                    operands.append(IROperand(type="", value=ret_parts[0]))
        elif opcode == "store":
            # store <ty> <val>, <ty>* <ptr>
            # e.g. store i32 50, ptr %3, align 4
            comma_parts = rest.split(",")
            if len(comma_parts) >= 2:
                src_parts = comma_parts[0].strip().split()
                dst_parts = comma_parts[1].strip().split()
                src_ty = src_parts[0] if len(src_parts) > 1 else ""
                src_val = src_parts[-1]
                dst_ty = dst_parts[0] if len(dst_parts) > 1 else ""
                dst_val = dst_parts[1] if len(dst_parts) > 1 else dst_parts[0]
                operands.append(IROperand(type=src_ty, value=src_val))
                operands.append(IROperand(type=dst_ty, value=dst_val))
        elif opcode in ("add", "sub", "mul", "sdiv", "udiv", "shl", "lshr", "ashr", "and", "or", "xor"):
            # %5 = add nsw i32 %4, 1
            # Clean modifiers like nsw, nuw
            sub_tokens = rest.split()
            mods = []
            while sub_tokens and sub_tokens[0] in ("nsw", "nuw", "exact"):
                mods.append(sub_tokens.pop(0))
            if sub_tokens:
                ty = sub_tokens[0]
                ops_str = " ".join(sub_tokens[1:])
                op_list = [o.strip() for o in ops_str.split(",")]
                for op_item in op_list:
                    operands.append(IROperand(type=ty, value=op_item))
        elif opcode == "icmp":
            # %cmp = icmp slt i32 %i, 10
            sub_tokens = rest.split()
            if len(sub_tokens) >= 3:
                cond_code = sub_tokens[0] # slt, eq, etc.
                ty = sub_tokens[1]
                ops_str = " ".join(sub_tokens[2:])
                op_list = [o.strip() for o in ops_str.split(",")]
                for op_item in op_list:
                    operands.append(IROperand(type=ty, value=op_item))

        # Extract all register uses / operands generally if not parsed above
        if not operands:
            matches = re.findall(r"(%[\w\.\-]+|@[\w\.\-]+|\b\d+\b)", rest)
            for m in matches:
                operands.append(IROperand(type="", value=m))

        return IRInstruction(
            opcode=opcode,
            result=result,
            operands=operands,
            raw_text=raw_line,
            comment=comment
        )

    def _resolve_cfg(self, module: IRModule):
        """Resolves predecessor and successor edges for every basic block in the module."""
        for func in module.functions:
            if func.is_declaration:
                continue

            # Clear existing edges
            for block in func.blocks:
                block.predecessors.clear()
                block.successors.clear()

            # Build name to block mapping
            block_map = {b.name: b for b in func.blocks}

            for idx, block in enumerate(func.blocks):
                term = block.get_terminator()
                if not term:
                    # Fallthrough to next block if no terminator
                    if idx + 1 < len(func.blocks):
                        next_b = func.blocks[idx + 1]
                        block.successors.add(next_b.name)
                        next_b.predecessors.add(block.name)
                    continue

                if term.opcode == "br":
                    if len(term.operands) == 1:
                        target = term.operands[0].value.lstrip("%")
                        block.successors.add(target)
                        if target in block_map:
                            block_map[target].predecessors.add(block.name)
                    elif len(term.operands) == 3:
                        target1 = term.operands[1].value.lstrip("%")
                        target2 = term.operands[2].value.lstrip("%")
                        block.successors.add(target1)
                        block.successors.add(target2)
                        if target1 in block_map:
                            block_map[target1].predecessors.add(block.name)
                        if target2 in block_map:
                            block_map[target2].predecessors.add(block.name)
